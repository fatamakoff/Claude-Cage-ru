func serviceHTTPFailure(action string, status int) error {
	reason, next := fmt.Sprintf("Служба вернула HTTP %d, конкретная причина пока не определена", status), failureHelp
	switch status {
	case http.StatusUnauthorized, http.StatusForbidden:
		reason, next = "Служба отклонила авторизацию этого подключения", "Подключитесь к текущей среде заново; если ошибка повторяется, обновите компоненты среды и попробуйте снова."
	case http.StatusNotFound, http.StatusGone:
		reason, next = "Целевое окно, файл или интерфейс службы больше не существует", "Снова откройте целевое окно или выберите файл заново; если среда устарела, сначала обновите компоненты среды."
	case http.StatusConflict:
		reason, next = "Целевое состояние изменилось или другая операция ещё не завершена", "Проверьте текущую страницу и целевой файл, затем повторите операцию."
	case http.StatusRequestEntityTooLarge:
		reason, next = "Файл или содержимое запроса превышает допустимый размер", "Уменьшите файл или обработайте его частями, затем повторите операцию."
	case http.StatusTooManyRequests:
		reason, next = "Служба временно ограничила число запросов", "Подождите немного и повторите, не нажимайте кнопку подряд."
	case http.StatusBadGateway, http.StatusServiceUnavailable:
		reason, next = "Служба внутри среды не готова или перестала отвечать", "Убедитесь, что среда запущена; если подключение не восстанавливается, проверьте состояние компонентов в настройках среды."
	case http.StatusGatewayTimeout:
		reason, next = "Истекло время ожидания ответа службы в среде", "Проверьте нагрузку среды и повторите позже; при постоянных тайм-аутах экспортируйте диагностический пакет."
	}
	return usererror.New(action, reason, next, nil)
}

